package fields

import (
	"fmt"
	"strings"
)

// DCGMExporterCSV renders the catalog as dcgm-exporter field lines (the file
// passed to dcgm-exporter with -f), for dcgm-exporter 4.8.x and earlier. Static fields are included so limits and
// maximum clocks arrive with every scrape, and the driver-version label.
func DCGMExporterCSV() string {
	var b strings.Builder
	b.WriteString("# InfraPulse field lines for dcgm-exporter 4.8.x and earlier (generated by `ipcollect fields --dcgm-exporter-csv`).\n")
	b.WriteString("# Do not load this file on dcgm-exporter 4.9.0 or later: it renamed most fields and rejects the\n")
	b.WriteString("# clock-event reasons line below.\n")
	b.WriteString("#\n")
	b.WriteString("# If dcgm-exporter already runs with a collectors file, ADD the lines you are missing to that file.\n")
	b.WriteString("# Do NOT replace it with this one: dcgm-exporter exports only what its file lists, so replacing it\n")
	b.WriteString("# would stop every metric of yours that is not here. Try the change on one node first:\n")
	b.WriteString("# dcgm-exporter refuses to start on a field name it does not accept. If your DCGM version rejects\n")
	b.WriteString("# a name, comment that line out; `ipcollect check` reports coverage.\n")
	b.WriteString("#\n")
	b.WriteString("# Format: DCGM field name, Prometheus metric type, help message.\n")
	current := Tier("")
	for _, f := range Catalog {
		if f.Tier != current {
			current = f.Tier
			fmt.Fprintf(&b, "\n# Tier %s\n", f.Tier)
		}
		fmt.Fprintf(&b, "%s, %s, %s\n", f.Name, f.Kind, f.ExporterHelp())
	}
	// dcgm-exporter attaches a "label" field to every metric. Its default file
	// carries the driver version this way; a custom file must list it too, or the
	// driver_version column stays empty.
	b.WriteString("\n# Labels (attached to every metric)\n")
	b.WriteString("DCGM_FI_DRIVER_VERSION, label, Driver version.\n")
	return b.String()
}

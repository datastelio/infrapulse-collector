package fields

import (
	"fmt"
	"strings"
)

// DCGMExporterCSV renders the catalog as dcgm-exporter field lines (the file
// passed to dcgm-exporter with -f) under the classic DCGM names, for
// dcgm-exporter 4.8.x and earlier. Static fields are included so limits and
// maximum clocks arrive with every scrape, and the driver-version label.
func DCGMExporterCSV() string { return exporterCSV(false) }

// DCGMExporterCSVV2 is the same list under the DCGM 4.7 names, for
// dcgm-exporter 4.9.0 and later. Fields 4.9 does not export are left out.
func DCGMExporterCSVV2() string { return exporterCSV(true) }

func exporterCSV(v2 bool) string {
	var b strings.Builder
	if v2 {
		b.WriteString("# InfraPulse field lines for dcgm-exporter 4.9.0 and later, DCGM 4.7 names (generated by `ipcollect fields --dcgm-exporter-csv --exporter 4.9`).\n")
		b.WriteString("# For dcgm-exporter 4.8.x and earlier use infrapulse-dcgm-fields.csv instead.\n")
	} else {
		b.WriteString("# InfraPulse field lines for dcgm-exporter 4.8.x and earlier (generated by `ipcollect fields --dcgm-exporter-csv`).\n")
		b.WriteString("# For dcgm-exporter 4.9.0 and later use infrapulse-dcgm-fields-4.9.csv instead.\n")
	}
	b.WriteString("# Format: DCGM field name, Prometheus metric type, help message.\n")
	b.WriteString("# Add the lines you are missing to the collectors file you already use; do not replace\n")
	b.WriteString("# your file with this one (infrapulse-merge-fields.sh does the merge and removes nothing).\n")
	b.WriteString("# If your DCGM version rejects a name, comment that line out; `ipcollect check` reports coverage.\n")
	if v2 {
		b.WriteString("# 4.9 rejects bitmask fields, so the clock-event (throttle) reasons bitmask is not here;\n")
		b.WriteString("# ipcollect derives it from the throttle-seconds counters below.\n")
	}
	current := Tier("")
	for _, f := range Catalog {
		name, help := f.Name, f.ExporterHelp()
		if v2 {
			if f.V2 == "" {
				continue
			}
			name, help = f.V2, f.V2Help
		}
		if f.Tier != current {
			current = f.Tier
			fmt.Fprintf(&b, "\n# Tier %s\n", f.Tier)
		}
		for _, line := range strings.Split(f.FileNote, "\n") {
			if line != "" {
				fmt.Fprintf(&b, "# %s\n", line)
			}
		}
		fmt.Fprintf(&b, "%s, %s, %s\n", name, f.Kind, help)
	}
	// dcgm-exporter attaches a "label" field to every metric. Its default file
	// carries the driver version this way; a custom file must list it too, or the
	// driver_version column stays empty.
	b.WriteString("\n# Labels (attached to every metric)\n")
	if v2 {
		b.WriteString(LabelDriverV2 + ", label, Driver version.\n")
	} else {
		b.WriteString(LabelDriver + ", label, Driver version.\n")
	}
	return b.String()
}

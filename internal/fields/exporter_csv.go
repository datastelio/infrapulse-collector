package fields

import (
	"fmt"
	"strings"
)

// DCGMExporterCSV renders the catalog as a dcgm-exporter custom metrics file
// (passed to dcgm-exporter with -f). Static fields are included so limits and
// maximum clocks arrive with every scrape, and the driver-version label.
func DCGMExporterCSV() string {
	var b strings.Builder
	b.WriteString("# InfraPulse field list for dcgm-exporter (generated by `ipcollect fields --dcgm-exporter-csv`).\n")
	b.WriteString("# Format: DCGM field name, Prometheus metric type, help message.\n")
	b.WriteString("# If your DCGM version rejects a name, comment that line out; `ipcollect check` reports coverage.\n")
	current := Tier("")
	for _, f := range Catalog {
		if f.Tier != current {
			current = f.Tier
			fmt.Fprintf(&b, "\n# Tier %s\n", f.Tier)
		}
		fmt.Fprintf(&b, "%s, %s, %s\n", f.Name, f.Kind, f.Help)
	}
	// dcgm-exporter attaches a "label" field to every metric. Its default file
	// carries the driver version this way; a custom file must list it too, or the
	// driver_version column stays empty.
	b.WriteString("\n# Labels (attached to every metric)\n")
	b.WriteString("DCGM_FI_DRIVER_VERSION, label, Driver version.\n")
	return b.String()
}
